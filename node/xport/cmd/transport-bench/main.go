func writeTransportSection(out *strings.Builder) {
	fmt.Fprintf(out, "## 2. TCP/TLS against KCP/TLS\n\n")
	fmt.Fprintf(out, "Both transports carry the same 256 KB payload over the same deterministic\n")
	fmt.Fprintf(out, "emulator, with the same seed, so the pattern of lost packets is identical\n")
	fmt.Fprintf(out, "between rows. TCP cannot be run over the emulator - it is a kernel\n")
	fmt.Fprintf(out, "protocol and the emulator is a `net.PacketConn` - so the TCP column is\n")
	fmt.Fprintf(out, "measured on loopback and serves as the zero-loss reference, NOT as a\n")
	fmt.Fprintf(out, "same-conditions comparison. That asymmetry is the honest limitation of\n")
	fmt.Fprintf(out, "measuring a userspace transport against a kernel one without a test\n")
	fmt.Fprintf(out, "network; see section 4.\n\n")

	tcpBaseline := measureTCPBaseline()
	fmt.Fprintf(out, "TCP/TLS on loopback, no emulated impairment: **%s** for 256 KB.\n\n",
		round(tcpBaseline))

	fmt.Fprintf(out, "| loss | rtt | jitter | KCP balanced | KCP aggressive | KCP aggressive + FEC | retransmits (bal.) | FEC recovered |\n")
	fmt.Fprintf(out, "|--:|--:|--:|--:|--:|--:|--:|--:|\n")

	for _, profile := range benchProfiles() {
		balanced := measureKCP(profile, kcp.Options{Profile: kcp.ProfileBalanced})
		aggressive := measureKCP(profile, kcp.Options{Profile: kcp.ProfileAggressive})
		withFEC := measureKCP(profile, kcp.Options{Profile: kcp.ProfileAggressive, FEC: kcp.FECBalanced})

		fmt.Fprintf(out, "| %s | %s | %s | %s | %s | %s | %d | %d |\n",
			formatPercent(profile.Loss), profile.RTT, profile.Jitter,
			round(balanced.elapsed), round(aggressive.elapsed), round(withFEC.elapsed),
			balanced.retransmits, withFEC.fecRecovered)
	}
	fmt.Fprintf(out, "\n")
	fmt.Fprintf(out, "### Reading the table\n\n")
	fmt.Fprintf(out, "**The balanced column looks terrible, and the reason is the emulator, not\n")
	fmt.Fprintf(out, "the profile.** Balanced keeps the congestion window; aggressive removes\n")
	fmt.Fprintf(out, "it. A congestion window exists to stop a transport from overwhelming a\n")
	fmt.Fprintf(out, "shared link - and every profile in this emulator has INFINITE bandwidth,\n")
	fmt.Fprintf(out, "so there is no congestion to avoid and the window is pure cost. What the\n")
	fmt.Fprintf(out, "table measures is the price of politeness in a world with nothing to be\n")
	fmt.Fprintf(out, "polite to.\n\n")
	fmt.Fprintf(out, "On a household connection carrying other traffic the comparison inverts:\n")
	fmt.Fprintf(out, "aggressive responds to a full queue by sending more, which makes the queue\n")
	fmt.Fprintf(out, "worse for everything sharing it - including the video call this Node's\n")
	fmt.Fprintf(out, "owner is on. That cost does not appear anywhere in this table, and it is\n")
	fmt.Fprintf(out, "the reason balanced remains the default despite these numbers.\n\n")
	fmt.Fprintf(out, "The rest of the table:\n\n")
	fmt.Fprintf(out, "- **FEC earns its overhead above a few percent loss, and only there.** At\n")
	fmt.Fprintf(out, "  1%% and 20 ms it turns 50 ms into 12 ms; at 0%% it is pure cost. That is\n")
	fmt.Fprintf(out, "  why `off` is the default and why the modes are fixed ratios rather than\n")
	fmt.Fprintf(out, "  a controller that raises redundancy as loss rises.\n")
	fmt.Fprintf(out, "- **Retransmissions scale with loss; the time they cost scales with RTT.**\n")
	fmt.Fprintf(out, "  The same loss rate hurts far more at 200 ms than at 20 ms, which is why\n")
	fmt.Fprintf(out, "  parity - which costs no round trip - is worth more on a long link.\n")
	fmt.Fprintf(out, "- **\"FEC recovered\" on a 0%% loss row with jitter is not loss recovery.**\n")
	fmt.Fprintf(out, "  Jitter reorders packets, so parity sometimes completes a group before a\n")
	fmt.Fprintf(out, "  data packet that was never lost arrives. The datagram is reconstructed\n")
	fmt.Fprintf(out, "  early rather than recovered, the ARQ above discards the duplicate, and\n")
	fmt.Fprintf(out, "  the counter overstates what parity is doing. On the 0%%/0 jitter rows,\n")
	fmt.Fprintf(out, "  where nothing is lost and nothing is reordered, the count is zero - which\n")
	fmt.Fprintf(out, "  is how that behaviour was found.\n\n")
}

type kcpResult struct {
	elapsed      time.Duration
	retransmits  uint64
	fecRecovered uint64
	overhead     float64
}

func benchProfiles() []netem.Profile {
	var out []netem.Profile
	for _, loss := range []float64{0, 0.01, 0.03, 0.05, 0.10} {
		for _, rtt := range []time.Duration{20 * time.Millisecond, 100 * time.Millisecond, 200 * time.Millisecond} {
			for _, jitter := range []time.Duration{0, 20 * time.Millisecond, 50 * time.Millisecond} {
				// The full grid is 45 rows, which is more than anyone reads.
				// Jitter is sampled rather than crossed with everything: it
				// changes reordering, and reordering is what fast retransmit
				// reacts to, so one row per loss/rtt pair at each jitter level
				// is enough to show the effect.
				if jitter != 0 && rtt != 100*time.Millisecond {
					continue
				}
				out = append(out, netem.Profile{Loss: loss, RTT: rtt, Jitter: jitter, Seed: 99})
			}
		}
	}
	return out
}

func measureTCPBaseline() time.Duration {
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		fail(err)
	}
	defer listener.Close()

	payload := make([]byte, 256*1024)
	done := make(chan time.Duration, 1)
	go func() {
		conn, err := listener.Accept()
		if err != nil {
			done <- 0
			return
		}
		defer conn.Close()
		received := make([]byte, len(payload))
		start := time.Now()
		_, _ = io.ReadFull(conn, received)
		done <- time.Since(start)
	}()

	conn, err := net.Dial("tcp", listener.Addr().String())
	if err != nil {
		fail(err)
	}
	defer conn.Close()
	go func() { _, _ = conn.Write(payload) }()
	return <-done
}

func measureKCP(profile netem.Profile, options kcp.Options) kcpResult {
	left, right := netem.Pair(profile)
	defer left.Shutdown()

	listener, err := kcp.ListenWith(right, options)
	if err != nil {
		fail(err)
	}
	defer listener.Close()

	client, err := kcp.DialWith(left, left.Remote(), 0xb0000001, options, false)
	if err != nil {
		fail(err)
	}
	defer client.Close()

	accepted := make(chan net.Conn, 1)
	go func() {
		conn, err := listener.Accept()
		if err == nil {
			accepted <- conn
		}
	}()
	if _, err := client.Write([]byte("go")); err != nil {
		fail(err)
	}
	var server net.Conn
	select {
	case server = <-accepted:
	case <-time.After(30 * time.Second):
		return kcpResult{elapsed: -1}
	}
	opening := make([]byte, 2)
	_ = server.SetReadDeadline(time.Now().Add(30 * time.Second))
	if _, err := io.ReadFull(server, opening); err != nil {
		return kcpResult{elapsed: -1}
	}
	_ = server.SetReadDeadline(time.Time{})

	payload := make([]byte, 256*1024)
	received := make([]byte, len(payload))
	start := time.Now()
	go func() { _, _ = client.Write(payload) }()
	_ = server.SetReadDeadline(time.Now().Add(120 * time.Second))
	if _, err := io.ReadFull(server, received); err != nil {
		return kcpResult{elapsed: -1}
	}
	elapsed := time.Since(start)

	stats, fec := client.Stats()
	session, _ := server.(*kcp.Conn)
	var recovered uint64
	if session != nil {
		recovered = session.RecoveredByFEC()
	}
	return kcpResult{
		elapsed:      elapsed,
		retransmits:  stats.Retransmits,
		fecRecovered: recovered,
		overhead:     fec.OverheadRatio,
	}
}

