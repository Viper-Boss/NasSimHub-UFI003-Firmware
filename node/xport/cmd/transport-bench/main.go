// Command transport-bench measures the handshake and the transports, and
// writes benchmarks/TRANSPORT_BENCHMARK.md.
//
// It is a program rather than a Go benchmark because the output is a document a
// person reads, not a number a machine compares - and because the transport
// grid needs a deterministic emulator underneath it, which `go test -bench`
// would run for a varying number of iterations.
//
// Everything it measures, it measures on THIS machine: an x86-64 container.
// That is stated in the document it writes, repeatedly, because the one
// conclusion nobody may draw from these numbers is what an MSM8916 will do.
// A Cortex-A53 at 1.2 GHz has no AES instructions worth the name, a fraction of
// the memory bandwidth, and a cache that a 1.2 KB ML-KEM key exchange does not
// fit comfortably into. The handshake cost there could plausibly be an order of
// magnitude different, in a direction this machine cannot predict.
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"fmt"
	"io"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"
	"time"

	"github.com/human-agent65535/nassimhub-node/proto"
	"github.com/human-agent65535/nassimhub-node/xport/kcp"
	"github.com/human-agent65535/nassimhub-node/xport/netem"
)

func main() {
	output := "benchmarks/TRANSPORT_BENCHMARK.md"
	if len(os.Args) > 1 {
		output = os.Args[1]
	}
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		fail(err)
	}

	var document strings.Builder
	writeHeader(&document)
	writeHandshakeSection(&document)
	writeTransportSection(&document)
	writeLimitations(&document)

	if err := os.WriteFile(output, []byte(document.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s\n", output)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "transport-bench:", err)
	os.Exit(1)
}

func writeHeader(out *strings.Builder) {
	fmt.Fprintf(out, "# Transport and handshake benchmarks\n\n")
	fmt.Fprintf(out, "Generated by `xport/cmd/transport-bench` on %s.\n\n",
		time.Now().UTC().Format("2006-01-02 15:04 UTC"))
	fmt.Fprintf(out, "| | |\n|---|---|\n")
	fmt.Fprintf(out, "| Go | %s |\n", runtime.Version())
	fmt.Fprintf(out, "| Platform | %s/%s |\n", runtime.GOOS, runtime.GOARCH)
	fmt.Fprintf(out, "| CPUs | %d |\n", runtime.NumCPU())
	fmt.Fprintf(out, "\n")
	fmt.Fprintf(out, "> **These numbers are from an x86-64 container. They say nothing about\n")
	fmt.Fprintf(out, "> MSM8916.** A Cortex-A53 at 1.2 GHz has different arithmetic throughput,\n")
	fmt.Fprintf(out, "> a smaller cache, and no comparable vector unit; a 1.2 KB hybrid key\n")
	fmt.Fprintf(out, "> exchange stresses all three. Treat the columns below as a comparison\n")
	fmt.Fprintf(out, "> BETWEEN options under identical conditions - which is what they are good\n")
	fmt.Fprintf(out, "> for - and not as a prediction of field performance.\n")
	fmt.Fprintf(out, "> **ARM64 measurement on real hardware is left to the hardware phase.**\n\n")
}

