func writeLimitations(out *strings.Builder) {
	fmt.Fprintf(out, "## 3. What the emulator models\n\n")
	fmt.Fprintf(out, "`xport/netem` applies independent per-packet loss, one-way delay, uniform\n")
	fmt.Fprintf(out, "jitter and duplication, from a seeded PRNG, to a `net.PacketConn`. A real\n")
	fmt.Fprintf(out, "KCP session with a real TLS handshake runs over it unmodified.\n\n")
	fmt.Fprintf(out, "It does **not** model:\n\n")
	fmt.Fprintf(out, "- **Bursty loss**, which is what cellular links actually produce. Independent\n")
	fmt.Fprintf(out, "  loss is the friendliest possible case for XOR parity, which recovers one\n")
	fmt.Fprintf(out, "  packet per group: a burst that takes two packets from one group is not\n")
	fmt.Fprintf(out, "  recoverable, so the FEC column here is an upper bound on its value.\n")
	fmt.Fprintf(out, "- **Bandwidth limits and queueing delay.** Every profile here has infinite\n")
	fmt.Fprintf(out, "  capacity, so the aggressive profile's disabled congestion window costs\n")
	fmt.Fprintf(out, "  nothing. On a real shared link it would.\n")
	fmt.Fprintf(out, "- **Competing traffic**, for the same reason.\n")
	fmt.Fprintf(out, "- **Radio handovers**, which stop delivery entirely for a few hundred\n")
	fmt.Fprintf(out, "  milliseconds and then resume - a pattern that punishes a short RTO.\n")
	fmt.Fprintf(out, "- **MTU discovery failures** and middleboxes that drop UDP outright, which\n")
	fmt.Fprintf(out, "  is the failure mode that decides whether KCP is usable at all on a\n")
	fmt.Fprintf(out, "  given network.\n\n")
	fmt.Fprintf(out, "Several of those would move the numbers in the direction that flatters\n")
	fmt.Fprintf(out, "this implementation less. The table is therefore a floor, and a\n")
	fmt.Fprintf(out, "comparison between options - not a prediction.\n\n")

	fmt.Fprintf(out, "## 4. What is left to the hardware phase\n\n")
	fmt.Fprintf(out, "**HARDWARE VERIFICATION REQUIRED:**\n\n")
	fmt.Fprintf(out, "- Handshake cost on a Cortex-A53. The byte counts above transfer; the\n")
	fmt.Fprintf(out, "  times do not.\n")
	fmt.Fprintf(out, "- Whether a hybrid handshake fits the device's memory budget while the\n")
	fmt.Fprintf(out, "  modem stack is also running.\n")
	fmt.Fprintf(out, "- KCP against a real cellular link, with real bursty loss and real\n")
	fmt.Fprintf(out, "  handovers.\n")
	fmt.Fprintf(out, "- Whether UDP survives the path at all, on the networks users have.\n")
	fmt.Fprintf(out, "- Battery and thermal cost of the aggressive profile's shorter timers.\n\n")
	fmt.Fprintf(out, "**HOST VERIFICATION REQUIRED:**\n\n")
	fmt.Fprintf(out, "- `SecP384r1MLKEM1024` (PQ_EXTREME) on Go 1.25 or later. This toolchain\n")
	fmt.Fprintf(out, "  does not implement it, so its row above is empty rather than estimated.\n")
	fmt.Fprintf(out, "- Reading back the negotiated group, which needs\n")
	fmt.Fprintf(out, "  `tls.ConnectionState.CurveID` - also Go 1.25.\n")
}

func round(d time.Duration) string {
	switch {
	case d < 0:
		return "failed"
	case d < time.Microsecond:
		return d.String()
	case d < time.Millisecond:
		return d.Round(time.Microsecond).String()
	case d < time.Second:
		return d.Round(100 * time.Microsecond).String()
	default:
		return d.Round(10 * time.Millisecond).String()
	}
}

func signedDuration(d time.Duration) string {
	if d >= 0 {
		return "+" + round(d)
	}
	return "-" + round(-d)
}

func humanBytes(b uint64) string {
	switch {
	case b < 1024:
		return fmt.Sprintf("%d B", b)
	case b < 1024*1024:
		return fmt.Sprintf("%.1f KB", float64(b)/1024)
	default:
		return fmt.Sprintf("%.1f MB", float64(b)/(1024*1024))
	}
}

func formatPercent(value float64) string {
	return fmt.Sprintf("%.0f%%", value*100)
}
