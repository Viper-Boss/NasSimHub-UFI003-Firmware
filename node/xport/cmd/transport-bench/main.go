type handshakeResult struct {
	name       string
	group      string
	available  bool
	median     time.Duration
	p90        time.Duration
	bytesOut   int
	bytesIn    int
	allocBytes uint64
	allocs     uint64
	note       string
}

func writeHandshakeSection(out *strings.Builder) {
	fmt.Fprintf(out, "## 1. TLS 1.3 handshake\n\n")
	fmt.Fprintf(out, "Loopback TCP, so the numbers are compute and bytes, not network.\n")
	fmt.Fprintf(out, "200 handshakes per row; median and 90th percentile.\n\n")

	cases := []struct {
		name  string
		group uint16
	}{
		{"classical baseline (X25519)", proto.GroupX25519},
		{"classical baseline (P-256)", proto.GroupP256},
		{"X25519MLKEM768 (PQ_STANDARD)", proto.GroupX25519MLKEM768},
		{"SecP384r1MLKEM1024 (PQ_EXTREME)", proto.GroupSecP384r1MLKEM1024},
	}

	var results []handshakeResult
	for _, testCase := range cases {
		results = append(results, measureHandshake(testCase.name, testCase.group))
	}

	fmt.Fprintf(out, "| key agreement | median | p90 | bytes client→server | bytes server→client | alloc/handshake | allocs |\n")
	fmt.Fprintf(out, "|---|--:|--:|--:|--:|--:|--:|\n")
	for _, result := range results {
		if !result.available {
			fmt.Fprintf(out, "| %s | — | — | — | — | — | — |\n", result.name)
			continue
		}
		fmt.Fprintf(out, "| %s | %s | %s | %d | %d | %s | %d |\n",
			result.name,
			round(result.median), round(result.p90),
			result.bytesOut, result.bytesIn,
			humanBytes(result.allocBytes), result.allocs)
	}
	fmt.Fprintf(out, "\n")

	for _, result := range results {
		if result.note != "" {
			fmt.Fprintf(out, "- **%s**: %s\n", result.name, result.note)
		}
	}

	// The comparison that matters: what post-quantum costs over classical.
	var classical, pq *handshakeResult
	for index := range results {
		switch results[index].group {
		case proto.GroupName(proto.GroupX25519):
			classical = &results[index]
		case proto.GroupName(proto.GroupX25519MLKEM768):
			pq = &results[index]
		}
	}
	if classical != nil && pq != nil && classical.available && pq.available {
		extraBytes := (pq.bytesOut + pq.bytesIn) - (classical.bytesOut + classical.bytesIn)
		fmt.Fprintf(out, "\n**What post-quantum costs here**: %+d bytes on the wire per handshake "+
			"(%d → %d), and %s of handshake time (%s → %s).\n",
			extraBytes,
			classical.bytesOut+classical.bytesIn, pq.bytesOut+pq.bytesIn,
			signedDuration(pq.median-classical.median), round(classical.median), round(pq.median))
		fmt.Fprintf(out, "\nThe byte count is the part that transfers to other hardware: "+
			"ML-KEM-768 keys and ciphertexts are the size they are everywhere. "+
			"The time is not - see the warning at the top.\n")
	}
	fmt.Fprintf(out, "\n")
}

func measureHandshake(name string, group uint16) handshakeResult {
	result := handshakeResult{name: name, group: proto.GroupName(group)}
	if !proto.BuildSupportsGroup(group) {
		result.note = fmt.Sprintf(
			"not implemented by %s. SecP384r1MLKEM1024 needs Go 1.25 or later. "+
				"**HOST VERIFICATION REQUIRED.**", runtime.Version())
		return result
	}

	certificate, leaf := benchCertificate()
	roots := x509.NewCertPool()
	roots.AddCert(leaf)
	curves := []tls.CurveID{tls.CurveID(group)}

	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		fail(err)
	}
	defer listener.Close()

	serverConfig := &tls.Config{
		Certificates:     []tls.Certificate{certificate},
		MinVersion:       tls.VersionTLS13,
		CurvePreferences: curves,
		// Session resumption would make later handshakes cheaper and measure
		// the wrong thing: what matters here is the cost of a full key
		// agreement, which is what a Node reconnecting after a reboot pays.
		SessionTicketsDisabled: true,
	}
	clientConfig := &tls.Config{
		RootCAs:                roots,
		ServerName:             "bench.local",
		MinVersion:             tls.VersionTLS13,
		CurvePreferences:       curves,
		SessionTicketsDisabled: true,
	}

	var wait sync.WaitGroup
	wait.Add(1)
	stop := make(chan struct{})
	go func() {
		defer wait.Done()
		for {
			conn, err := listener.Accept()
			if err != nil {
				select {
				case <-stop:
					return
				default:
					return
				}
			}
			go func() {
				server := tls.Server(conn, serverConfig)
				if server.Handshake() == nil {
					buffer := make([]byte, 1)
					_ = server.SetReadDeadline(time.Now().Add(time.Second))
					_, _ = io.ReadFull(server, buffer)
				}
				_ = conn.Close()
			}()
		}
	}()

	const rounds = 200
	durations := make([]time.Duration, 0, rounds)
	var counted *countingConn

	// Warm up, so the first allocation of a code path is not charged to the
	// measurement.
	for i := 0; i < 20; i++ {
		runHandshake(listener.Addr().String(), clientConfig, nil)
	}

	var before, after runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&before)

	for i := 0; i < rounds; i++ {
		var counter countingConn
		start := time.Now()
		runHandshake(listener.Addr().String(), clientConfig, &counter)
		durations = append(durations, time.Since(start))
		counted = &counter
	}
	runtime.ReadMemStats(&after)

	close(stop)
	_ = listener.Close()
	wait.Wait()

	sort.Slice(durations, func(i, j int) bool { return durations[i] < durations[j] })
	result.available = true
	result.median = durations[len(durations)/2]
	result.p90 = durations[(len(durations)*9)/10]
	if counted != nil {
		result.bytesOut = counted.written
		result.bytesIn = counted.read
	}
	result.allocBytes = (after.TotalAlloc - before.TotalAlloc) / rounds
	result.allocs = (after.Mallocs - before.Mallocs) / rounds
	return result
}

func runHandshake(address string, config *tls.Config, counter *countingConn) {
	raw, err := net.DialTimeout("tcp", address, 5*time.Second)
	if err != nil {
		fail(err)
	}
	var underlying net.Conn = raw
	if counter != nil {
		counter.Conn = raw
		underlying = counter
	}
	client := tls.Client(underlying, config)
	if err := client.Handshake(); err != nil {
		fail(err)
	}
	_, _ = client.Write([]byte("x"))
	_ = raw.Close()
}

type countingConn struct {
	net.Conn
	read    int
	written int
}

func (c *countingConn) Read(p []byte) (int, error) {
	n, err := c.Conn.Read(p)
	c.read += n
	return n, err
}

func (c *countingConn) Write(p []byte) (int, error) {
	n, err := c.Conn.Write(p)
	c.written += n
	return n, err
}

func benchCertificate() (tls.Certificate, *x509.Certificate) {
	public, private, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		fail(err)
	}
	template := &x509.Certificate{
		SerialNumber:          big.NewInt(7),
		Subject:               pkix.Name{CommonName: "bench"},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(time.Hour),
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageCertSign,
		BasicConstraintsValid: true,
		IsCA:                  true,
		DNSNames:              []string{"bench.local"},
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, public, private)
	if err != nil {
		fail(err)
	}
	leaf, err := x509.ParseCertificate(der)
	if err != nil {
		fail(err)
	}
	return tls.Certificate{Certificate: [][]byte{der}, PrivateKey: private, Leaf: leaf}, leaf
}

